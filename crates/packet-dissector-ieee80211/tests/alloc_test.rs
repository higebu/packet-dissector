//! Zero-allocation dissection tests for the IEEE 802.11 dissector.

use packet_dissector_core::dissector::{DispatchHint, Dissector};
use packet_dissector_core::packet::DissectBuffer;
use packet_dissector_ieee80211::Ieee80211Dissector;
use packet_dissector_test_alloc::{count_allocs, setup_counting_allocator};

setup_counting_allocator!();

#[rustfmt::skip]
const QOS_DATA: &[u8] = &[
    0x88, 0x01, 0x2C, 0x00, // QoS Data, To DS
    0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
    0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB,
    0xCC, 0xDD, 0xEE, 0xFF, 0x00, 0x01,
    0x10, 0x00, // Sequence Control
    0x05, 0x00, // QoS Control
    0xAA, 0xAA, 0x03, 0x00, 0x00, 0x00, 0x08, 0x00, // LLC/SNAP → IPv4
    0x45, 0x00,
];

#[rustfmt::skip]
const BEACON: &[u8] = &[
    0x80, 0x00, 0x00, 0x00, // Beacon
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
    0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
    0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, // Timestamp
    0x64, 0x00, 0x11, 0x04, // Beacon Interval, Capability
    0x00, 0x04, b't', b'e', b's', b't', // SSID
    0x01, 0x04, 0x82, 0x84, 0x8B, 0x96, // Supported Rates
    0x03, 0x01, 0x06, // DSSS Parameter Set
    0x30, 0x14, 0x01, 0x00, // RSN: version 1
    0x00, 0x0F, 0xAC, 0x04, // group CCMP-128
    0x01, 0x00, 0x00, 0x0F, 0xAC, 0x04, // pairwise CCMP-128
    0x01, 0x00, 0x00, 0x0F, 0xAC, 0x02, // AKM PSK
    0x0C, 0x00, // RSN Capabilities
];

#[test]
fn zero_alloc_dissect_ieee80211_qos_data() {
    let mut buf = DissectBuffer::new();
    let allocs = count_allocs(|| {
        buf.clear();
        let r = Ieee80211Dissector.dissect(QOS_DATA, &mut buf, 0).unwrap();
        assert_eq!(r.next, DispatchHint::ByLlcSap(0xAA));
    });
    assert_eq!(
        allocs, 0,
        "802.11 QoS Data dissect allocated {allocs} times"
    );
}

#[test]
fn zero_alloc_dissect_ieee80211_beacon() {
    let mut buf = DissectBuffer::new();
    // Warm up so that the field buffer has grown to the beacon's size.
    Ieee80211Dissector.dissect(BEACON, &mut buf, 0).unwrap();
    let allocs = count_allocs(|| {
        buf.clear();
        Ieee80211Dissector.dissect(BEACON, &mut buf, 0).unwrap();
    });
    assert_eq!(allocs, 0, "802.11 Beacon dissect allocated {allocs} times");
    assert_eq!(buf.layers()[0].name, "IEEE802.11");
}

#[test]
fn zero_alloc_dissect_ieee80211_amsdu() {
    #[rustfmt::skip]
    let raw: &[u8] = &[
        0x88, 0x02, 0x00, 0x00, // QoS Data, From DS
        0xCC, 0xDD, 0xEE, 0xFF, 0x00, 0x01,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x00, 0x00,
        0x80, 0x00, // QoS Control: A-MSDU Present
        0xCC, 0xDD, 0xEE, 0xFF, 0x00, 0x01, 0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB,
        0x00, 0x0A, 0xAA, 0xAA, 0x03, 0x00, 0x00, 0x00, 0x08, 0x00, 0x45, 0x00,
        0xCC, 0xDD, 0xEE, 0xFF, 0x00, 0x01, 0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB,
        0x00, 0x0A, 0xAA, 0xAA, 0x03, 0x00, 0x00, 0x00, 0x08, 0x00, 0x45, 0x00,
    ];
    let mut buf = DissectBuffer::new();
    Ieee80211Dissector.dissect(raw, &mut buf, 0).unwrap();
    let allocs = count_allocs(|| {
        buf.clear();
        Ieee80211Dissector.dissect(raw, &mut buf, 0).unwrap();
    });
    assert_eq!(allocs, 0, "802.11 A-MSDU dissect allocated {allocs} times");
    assert_eq!(buf.embedded_payloads().len(), 2);
}
