use criterion::{Criterion, Throughput, criterion_group, criterion_main};
use packet_dissector_core::dissector::Dissector;
use packet_dissector_core::packet::DissectBuffer;
use packet_dissector_xnap::XnapDissector;
use std::hint::black_box;

/// Handover Request Acknowledge with data forwarding GTP tunnels (pycrate APER encoding).
fn build_packet() -> Vec<u8> {
    vec![
        0x20, 0x00, 0x00, 0x58, 0x00, 0x00, 0x04, 0x00, 0x49, 0x40, 0x02, 0x00, 0x64, 0x00, 0x4f,
        0x40, 0x02, 0x00, 0xc8, 0x00, 0x2a, 0x40, 0x3d, 0x01, 0x00, 0x01, 0x70, 0x10, 0x08, 0x08,
        0x14, 0x0d, 0x88, 0x08, 0xe0, 0x00, 0x20, 0x3e, 0x0a, 0x0a, 0x00, 0x01, 0x00, 0x00, 0x50,
        0x01, 0x01, 0xf0, 0x0a, 0x0a, 0x00, 0x02, 0x00, 0x00, 0x50, 0x02, 0x0a, 0x00, 0x03, 0xe0,
        0x0a, 0x0a, 0x00, 0x03, 0x00, 0x00, 0x50, 0x03, 0x20, 0x40, 0x7c, 0x0a, 0x0a, 0x00, 0x04,
        0x00, 0x00, 0x50, 0x04, 0x00, 0x02, 0x00, 0x00, 0x50, 0x00, 0x4d, 0x40, 0x04, 0x03, 0x0a,
        0x0b, 0x0c,
    ]
}

fn bench_dissect(c: &mut Criterion) {
    let dissector = XnapDissector;
    let data = build_packet();
    let mut buf = DissectBuffer::new();

    let mut group = c.benchmark_group("dissect");
    group.throughput(Throughput::Bytes(data.len() as u64));
    group.bench_function("xnap", |b| {
        b.iter(|| {
            buf.clear();
            dissector.dissect(black_box(&data), &mut buf, 0).unwrap();
        });
    });
    group.finish();
}

criterion_group!(benches, bench_dissect);
criterion_main!(benches);
