use criterion::{Criterion, Throughput, criterion_group, criterion_main};
use packet_dissector_core::dissector::Dissector;
use packet_dissector_core::packet::DissectBuffer;
use packet_dissector_f1ap::F1apDissector;
use std::hint::black_box;

/// UE Context Setup Response with a DRBs Setup List (pycrate APER encoding).
fn build_packet() -> Vec<u8> {
    vec![
        0x40, 0x05, 0x00, 0x45, 0x00, 0x00, 0x04, 0x00, 0x28, 0x00, 0x02, 0x00, 0x01, 0x00, 0x29,
        0x00, 0x02, 0x00, 0x07, 0x00, 0x27, 0x00, 0x04, 0x00, 0x02, 0x5c, 0x00, 0x00, 0x1b, 0x40,
        0x2a, 0x04, 0x00, 0x1a, 0x40, 0x0c, 0x40, 0x06, 0x00, 0x7c, 0x0a, 0x00, 0x00, 0x02, 0x00,
        0x00, 0x10, 0x01, 0x00, 0x1a, 0x40, 0x15, 0x00, 0xc0, 0x1f, 0x0a, 0x00, 0x00, 0x02, 0x00,
        0x00, 0x10, 0x02, 0x00, 0x7c, 0x0a, 0x00, 0x00, 0x03, 0x00, 0x00, 0x10, 0x03,
    ]
}

fn bench_dissect(c: &mut Criterion) {
    let dissector = F1apDissector;
    let data = build_packet();
    let mut buf = DissectBuffer::new();

    let mut group = c.benchmark_group("dissect");
    group.throughput(Throughput::Bytes(data.len() as u64));
    group.bench_function("f1ap", |b| {
        b.iter(|| {
            buf.clear();
            dissector.dissect(black_box(&data), &mut buf, 0).unwrap();
        });
    });
    group.finish();
}

criterion_group!(benches, bench_dissect);
criterion_main!(benches);
