#[cfg(test)]
mod tests {
    //! # 3GPP TS 38.473 Protocol IE ID Coverage
    //!
    //! | Spec Section | Description                            | Test                |
    //! |--------------|----------------------------------------|---------------------|
    //! | 9.4.7        | Known constants                        | known_values        |
    //! | 9.4.7        | Every assigned value is named          | all_assigned_named  |
    //! | 9.4.7        | Unassigned values                      | unknown_values      |

    use super::*;

    /// Values not assigned to any `id-` constant in TS 38.473 v19.4.0,
    /// Section 9.4.7.
    const UNASSIGNED: &[u16] = &[
        8, 10, 11, 103, 104, 110, 143, 166, 167, 169, 245, 367, 368, 388, 563, 572, 900,
    ];

    #[test]
    fn known_values() {
        assert_eq!(ie_id_name(0), "Cause");
        assert_eq!(ie_id_name(470), "BroadcastMRBs-ToBeModified-List");
        assert_eq!(ie_id_name(928), "CSI-IMResourceSetToReleaseList");
    }

    #[test]
    fn all_assigned_named() {
        for value in 0..=928u16 {
            let named = ie_id_name(value) != "Unknown";
            assert_eq!(named, !UNASSIGNED.contains(&value), "value {value}");
        }
    }

    #[test]
    fn unknown_values() {
        assert_eq!(ie_id_name(929), "Unknown");
        assert_eq!(ie_id_name(u16::MAX), "Unknown");
    }
}
