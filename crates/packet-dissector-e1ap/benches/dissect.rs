use criterion::{Criterion, Throughput, criterion_group, criterion_main};
use packet_dissector_core::dissector::Dissector;
use packet_dissector_core::packet::DissectBuffer;
use packet_dissector_e1ap::E1apDissector;
use std::hint::black_box;

/// Bearer Context Setup Response (NG-RAN) with PDU session and DRB lists (pycrate APER encoding).
fn build_packet() -> Vec<u8> {
    vec![
        0x20, 0x08, 0x00, 0x7c, 0x00, 0x00, 0x03, 0x00, 0x02, 0x00, 0x02, 0x00, 0x0a, 0x00, 0x03,
        0x00, 0x02, 0x00, 0x14, 0x00, 0x10, 0x40, 0x69, 0x40, 0x00, 0x01, 0x00, 0x2e, 0x40, 0x62,
        0x01, 0x78, 0x01, 0x10, 0x07, 0xc0, 0xc0, 0xa8, 0x00, 0x01, 0xab, 0xcd, 0x00, 0x01, 0x20,
        0x1f, 0xc0, 0xa8, 0x00, 0x02, 0xab, 0xcd, 0x00, 0x02, 0x04, 0x80, 0x00, 0x0f, 0x80, 0xc0,
        0xa8, 0x00, 0x03, 0xab, 0xcd, 0x00, 0x03, 0x00, 0x80, 0x81, 0x00, 0x0a, 0x0f, 0x40, 0x50,
        0x07, 0xc0, 0xc0, 0xa8, 0x00, 0x04, 0xab, 0xcd, 0x00, 0x04, 0x00, 0x0f, 0x80, 0xc0, 0xa8,
        0x00, 0x05, 0xab, 0xcd, 0x00, 0x05, 0x20, 0x04, 0x80, 0x09, 0xa0, 0x00, 0x02, 0x01, 0xf0,
        0xc0, 0xa8, 0x00, 0x06, 0xab, 0xcd, 0x00, 0x06, 0x00, 0x06, 0x00, 0x1f, 0xc0, 0xa8, 0x00,
        0x07, 0xab, 0xcd, 0x00, 0x07, 0x00, 0x01, 0x80,
    ]
}

fn bench_dissect(c: &mut Criterion) {
    let dissector = E1apDissector;
    let data = build_packet();
    let mut buf = DissectBuffer::new();

    let mut group = c.benchmark_group("dissect");
    group.throughput(Throughput::Bytes(data.len() as u64));
    group.bench_function("e1ap", |b| {
        b.iter(|| {
            buf.clear();
            dissector.dissect(black_box(&data), &mut buf, 0).unwrap();
        });
    });
    group.finish();
}

criterion_group!(benches, bench_dissect);
criterion_main!(benches);
