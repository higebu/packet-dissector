#[cfg(test)]
mod tests {
    //! # 3GPP TS 38.413 IE ID Coverage
    //!
    //! | Spec Section | Description                          | Test                   |
    //! |--------------|--------------------------------------|------------------------|
    //! | 9.4.7        | Known ProtocolIE-ID constants        | known_ie_ids           |
    //! | 9.4.7        | Every assigned ID 0..=496 has a name | all_assigned_ids_named |
    //! | 9.4.7        | Unassigned IDs                       | unknown_ie_id          |

    use super::*;

    /// Values not assigned to any `id-` constant in TS 38.413 v19.3.0,
    /// Section 9.4.7.
    const UNASSIGNED: &[u16] = &[113, 308, 320, 321, 322, 330];

    #[test]
    fn known_ie_ids() {
        assert_eq!(ie_id_name(0), "AllowedNSSAI");
        assert_eq!(ie_id_name(10), "AMF-UE-NGAP-ID");
        assert_eq!(
            ie_id_name(18),
            "CoreNetworkAssistanceInformationForInactive"
        );
        assert_eq!(ie_id_name(43), "NGRAN-CGI");
        assert_eq!(ie_id_name(74), "PDUSessionResourceSetupListSUReq");
        assert_eq!(ie_id_name(139), "UL-NGU-UP-TNLInformation");
        assert_eq!(ie_id_name(151), "MaximumIntegrityProtectedDataRate-DL");
        assert_eq!(ie_id_name(483), "AdditionalULI");
        assert_eq!(ie_id_name(496), "AIoT-SecurityInfo");
    }

    #[test]
    fn all_assigned_ids_named() {
        for id in 0..=496u16 {
            let named = ie_id_name(id) != "Unknown";
            assert_eq!(named, !UNASSIGNED.contains(&id), "id {id}");
        }
    }

    #[test]
    fn unknown_ie_id() {
        assert_eq!(ie_id_name(497), "Unknown");
        assert_eq!(ie_id_name(9999), "Unknown");
    }
}
