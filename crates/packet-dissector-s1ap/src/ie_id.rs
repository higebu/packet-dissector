#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn all_ie_ids_named() {
        let named = (0..=u16::MAX)
            .filter(|id| ie_id_name(*id) != "Unknown")
            .count();
        assert_eq!(named, 336);
        assert_eq!(ie_id_name(0), "MME-UE-S1AP-ID");
        assert_eq!(ie_id_name(26), "NAS-PDU");
        assert_eq!(ie_id_name(5), "Unknown");
    }
}
